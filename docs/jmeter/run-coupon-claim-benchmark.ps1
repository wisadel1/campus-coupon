    [Parameter(Mandatory = $true)]
    [string]$TemplateNo,

    [Parameter(Mandatory = $true)]
    [long]$UserIdStart,

    [Parameter(Mandatory = $true)]
    [string]$JMeterBat,

    [string]$BaseUrl = "http://localhost:8080",
    [int]$Threads = 100,
    [int]$RampUp = 2,
    [int]$Loops = 5,
    [string]$Scenario = "M4-claim",
    [string]$OutputRoot = ".\benchmark-results"
)

$ErrorActionPreference = "Stop"

function Escape-Xml([string]$Value) {
    return [System.Security.SecurityElement]::Escape($Value)
}

# Validate inputs before creating test artifacts.
if (-not (Test-Path -LiteralPath $JMeterBat -PathType Leaf)) {
    throw "找不到 JMeter：$JMeterBat"
}
if ($Threads -lt 1 -or $RampUp -lt 0 -or $Loops -lt 1) {
    throw "Threads 和 Loops 必须大于 0，RampUp 不能小于 0。"
}
if ($UserIdStart -lt 0) {
    throw "UserIdStart 不能小于 0。"
}

$requestCount = $Threads * $Loops
$lastUserId = $UserIdStart + $requestCount - 1
$stamp = Get-Date -Format "yyyyMMdd-HHmmss"
$safeScenario = ($Scenario -replace '[^\w.-]', '_')
$runDir = Join-Path $OutputRoot "$safeScenario-$stamp"
New-Item -ItemType Directory -Path $runDir -Force | Out-Null

$csvPath = Join-Path $runDir "claim-users.csv"
$jmxPath = Join-Path $runDir "coupon-claim.jmx"
$jtlPath = Join-Path $runDir "results.jtl"
$htmlPath = Join-Path $runDir "html-report"
$logPath = Join-Path $runDir "jmeter.log"
$summaryPath = Join-Path $runDir "run-summary.txt"

# One distinct user ID per sampler execution. No header row.
$csvLines = for ($i = 0; $i -lt $requestCount; $i++) {
    [string]($UserIdStart + $i)
}
[System.IO.File]::WriteAllLines(
    $csvPath,
    $csvLines,
    [System.Text.UTF8Encoding]::new($false)
)

