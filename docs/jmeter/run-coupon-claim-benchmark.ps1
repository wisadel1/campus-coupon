# Split BaseUrl into protocol/host/port for JMeter HTTP defaults.
$uri = [System.Uri]$BaseUrl
$protocol = $uri.Scheme
$hostName = $uri.Host
$port = if ($uri.IsDefaultPort) { if ($protocol -eq "https") { 443 } else { 80 } } else { $uri.Port }

$args = @(
    "-n", "-t", "`"$jmxPath`"",
    "-l", "`"$jtlPath`"",
    "-e", "-o", "`"$htmlPath`"",
    "-j", "`"$logPath`"",
    "-JtemplateNo=$TemplateNo",
    "-Jprotocol=$protocol",
    "-Jhost=$hostName",
    "-Jport=$port",
    "-Jthreads=$Threads",
    "-JrampUp=$RampUp",
    "-Jloops=$Loops",
    "-JbaseUrl=$BaseUrl"
)

Write-Host ""
Write-Host "场景：$Scenario"
Write-Host "接口：$BaseUrl/api/coupon/claim"
Write-Host "线程：$Threads；Ramp-up：$RampUp 秒；每线程循环：$Loops"
Write-Host "请求总数：$requestCount"
Write-Host "用户 ID：$UserIdStart 至 $lastUserId"
Write-Host "结果目录：$((Resolve-Path $runDir).Path)"
Write-Host ""
Write-Warning "脚本不会清理或重置 MySQL/Redis。运行前必须确保这些用户尚未领取该模板，并且 Redis 库存与数据库库存已正确初始化。"

$process = Start-Process -FilePath $JMeterBat -ArgumentList $args -Wait -PassThru -NoNewWindow
$exitCode = $process.ExitCode

$summary = @"
Scenario: $Scenario
Started: $stamp
BaseUrl: $BaseUrl
Endpoint: POST /api/coupon/claim
TemplateNo: $TemplateNo
Threads: $Threads
RampUpSeconds: $RampUp
LoopsPerThread: $Loops
ExpectedRequests: $requestCount
UserIdRange: $UserIdStart - $lastUserId
JMeterExitCode: $exitCode
JTL: $jtlPath
HTMLReport: $htmlPath
JMeterLog: $logPath
"@
